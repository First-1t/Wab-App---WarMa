// สัดส่วนน้ำแต่ละระยะ: ปลูก–งอก / สร้างทรงพุ่ม–เริ่มลงหัว / หัวขยาย / สุกแก่
const PHASE_SHARE = [0.15, 0.25, 0.45, 0.15];

const round10 = (n: number) => Math.round(n / 10) * 10;
const fmtKg = (n: number) => round10(n).toLocaleString('en-US');

function phases(days: number) {
  const d1 = Math.round(days * 0.2);
  const d2 = Math.round(days * 0.45);
  const d3 = Math.round(days * 0.85);
  return [
    `ปลูก–งอก (วันที่ 1–${d1})`,
    `สร้างทรงพุ่ม–เริ่มลงหัว (วันที่ ${d1 + 1}–${d2})`,
    `หัวขยาย (วันที่ ${d2 + 1}–${d3})`,
    `สุกแก่–ขุด (วันที่ ${d3 + 1}–${days})`,
  ];
}

const scenarios = varieties.flatMap((v) =>
  cases.map((c) => {
    const waterPerRai = round10(c.need * v.waterFactor);
    const names = phases(v.days);
    // ระยะสุดท้ายที่ "งดให้น้ำ" = 0 แล้วย้ายน้ำส่วนนั้นไปช่วงหัวขยาย
    const share = c.freq[3].startsWith('งด')
      ? [PHASE_SHARE[0], PHASE_SHARE[1], PHASE_SHARE[2] + PHASE_SHARE[3], 0]
      : PHASE_SHARE;
    return {
      name: `มันฝรั่ง${v.name} ${c.season} น้ำ${c.level}`,
      crop: v.name,
      season: c.season,
      level: c.level,
      waterPerRai,
      minRatio: c.minRatio,
      maxRatio: c.maxRatio,
      expectedYield: `${fmtKg(v.yieldKg[0] * c.yieldFactor)}–${fmtKg(v.yieldKg[1] * c.yieldFactor)} กก./ไร่`,
      risk: c.risk,
      advice: [...c.advice, v.tip],
      schedule: names.map((phase, i) => ({
        phase,
        freq: c.freq[i],
        amount: round10(waterPerRai * share[i]),
      })),
    };
  }),
);

async function main() {
  if (process.argv.includes('--reset')) {
    const { count } = await prisma.scenario.deleteMany();
    console.log(`ลบข้อมูลเดิม ${count} scenario`);
  } else {
    const count = await prisma.scenario.count();
    if (count > 0) {
      console.log(`มีข้อมูลอยู่แล้ว ${count} scenario — ข้ามการ seed`);
      return;
    }
  }
  await prisma.scenario.createMany({ data: scenarios });
  console.log(`เพิ่มข้อมูลเริ่มต้น ${scenarios.length} scenario เรียบร้อย`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
