// สัดส่วนน้ำแต่ละระยะ: ปลูก–ตั้งตัว / สร้างลำต้นและใบ / สะสมแป้ง / ก่อนเก็บเกี่ยว
// มันสำปะหลังงดน้ำช่วงก่อนขุดเพื่อเพิ่มเปอร์เซ็นต์แป้ง
const PHASE_SHARE = [0.4, 0.35, 0.25, 0];

const round10 = (n: number) => Math.round(n / 10) * 10;
const fmtKg = (n: number) => (Math.round(n / 100) * 100).toLocaleString('en-US');

function phases(months: number) {
  return [
    'ปลูก–ตั้งตัว (เดือนที่ 1–2)',
    'สร้างลำต้นและใบ (เดือนที่ 3–5)',
    `สะสมแป้ง หัวขยาย (เดือนที่ 6–${months - 2})`,
    `ก่อนเก็บเกี่ยว (เดือนที่ ${months - 1}–${months})`,
  ];
}

const scenarios = varieties.flatMap((v) =>
  cases.map((c) => {
    const waterPerRai = round10(c.need * v.waterFactor);
    return {
      name: `มันสำปะหลัง${v.name} ${c.season} น้ำ${c.level}`,
      crop: v.name,
      season: c.season,
      level: c.level,
      waterPerRai,
      minRatio: c.minRatio,
      maxRatio: c.maxRatio,
      expectedYield: `${fmtKg(v.yieldKg[0] * c.yieldFactor)}–${fmtKg(v.yieldKg[1] * c.yieldFactor)} กก./ไร่ (หัวสด)`,
      risk: c.risk,
      advice: [...c.advice, v.tip],
      schedule: phases(v.months).map((phase, i) => ({
        phase,
        freq: c.freq[i],
        amount: round10(waterPerRai * PHASE_SHARE[i]),
      })),
    };
  }),
);

async function main() {
  if (process.argv.includes('--reset')) {
    const { count } = await prisma.scenario.deleteMany();
    console.log(`ลบข้อมูลเดิม ${count} scenario`);
  } else {
    const count = await prisma.scenario.count();
    if (count > 0) {
      console.log(`มีข้อมูลอยู่แล้ว ${count} scenario — ข้ามการ seed`);
      return;
    }
  }
  await prisma.scenario.createMany({ data: scenarios });
  console.log(`เพิ่มข้อมูลเริ่มต้น ${scenarios.length} scenario เรียบร้อย`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
